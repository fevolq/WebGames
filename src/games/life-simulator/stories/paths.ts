export const pathFor = (life: Life) => paths.find(item => item.id === life.path);
export function pathEvents(world: WorldId): EventCandidate[] {
  return paths.filter(item => item.world === world).flatMap(item => item.stages.map((stage, index) => {
    const id = `${item.id}-${index}`;
    const done = `${id}:done`;
    const won = `${id}:won`;
    return {
      minAge: (world === 'cultivation' ? [20, 42, 78] : [20, 32, 50])[index],
      affinity: item.stat, weight: 3,
      eligible: (life: Life) => life.path === item.id && (index === 0 || has(life, `${item.id}-${index - 1}:done`)),
      scene: {
        id, age: 0, kind: 'main' as const, title: stage[0],
        text: (life: Life) => `${index > 0 && !has(life, `${item.id}-${index - 1}:won`) ? '此前的经历没有给你一个轻易的答案。你带着学到的本领，也带着尚未补上的缺口，走到了新的岔口。\n\n' : ''}${stage[1]}`,
        choices: [
          { id: 'commit', label: stage[2], hint: '尝试推进，可能赢得机会，也可能损失生计与健康', outcome: outcome(''), risk: {
            stat: item.stat, difficulty: 5 + index * 3,
            success: outcome(stage[3], { stats: { [item.stat]: 2 }, wealth: 9, peace: 5, flags: [done, won] }),
            failure: outcome(stage[4], { stats: { [item.stat]: 1 }, wealth: -10, health: -5, peace: -4, flags: [done] }),
          } },
          choice('steady', '从能承担的部分做起', '积累经验，进展较慢', stage[5], { stats: { [item.stat]: 1 }, wealth: 3, peace: 5, flags: [done] }),
          choice('pause', '先顾好自己的生活', '放下这次机会，恢复身心', '你向相关的人说明了自己的处境，把时间留给休息和眼前的生活。这次机会过去了，往后的路仍然可以重新选择。', { health: 7, peace: 6, flags: [done] }),
        ],
      },
    };
  }));
}
