export function everydayEvents(world: WorldId): EventCandidate[] {
  return [true, false].flatMap(child => (child ? childhood[world] : ordinary[world]).map(([id, title, text, stat, action, result], index) => ({
    minAge: child ? (index === 2 ? 7 : index === 4 ? 6 : 3) : 18, maxAge: child ? 15 : undefined, affinity: stat,
    scene: { id: `${world}-${child ? 'child' : 'day'}-${id}`, age: 0, kind: 'life' as const, title,
      text: (life: Life) => `${child ? `在${originFor(life).place}长大的日子里，你开始有了自己的记忆。\n\n` : ''}${text}`,
      choices: [
        choice('try', action, '培养当下的本领，也会影响以后的机会', result, { stats: { [stat]: 1 }, health: child ? 2 : index === 0 ? 10 : 3, wealth: !child && index === 5 ? 7 : 0, peace: 4, flags: [`interest:${stat}`] }),
        choice('together', child ? '拉着伙伴一起试试' : '与熟悉的人一起度过这段时间', '相处也会改变彼此的关系', life => `${journeyRelations(life).friend.name}有自己的想法。你们商量了一个两人都能接受的安排，没有把谁留在一旁。事情做得慢一点，却多了一份可以一起回忆的经过。`, { links: { friend: 8 }, stats: { charm: 1 }, peace: 5 }),
        choice('quiet', child ? '先在旁边看一看' : '留一点时间照顾自己', '不必抓住每一次机会', '你没有催自己立刻做得很好。安静地看过、认真地休息，也是这段日子的一部分。', { health: 6, peace: 7, stats: { spirit: 1 } }),
      ],
    },
  })));
}
